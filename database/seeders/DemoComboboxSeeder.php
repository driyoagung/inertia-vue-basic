<?php

namespace Database\Seeders;

use App\Models\Task;
use App\Models\User;
use Illuminate\Database\Seeder;

class DemoComboboxSeeder extends Seeder
{
    public function run(): void
    {
        if (User::count() === 0) {
            User::factory()->count(8)->create();
        }

        $categories = \App\Models\Category::all();
        $users = User::all();

        if ($categories->isEmpty() || $users->isEmpty()) {
            return;
        }

        $tasks = [
            ['title' => 'Bangun dashboard admin', 'priority' => 'high', 'status' => 'in_progress'],
            ['title' => 'Refactor modul autentikasi', 'priority' => 'medium', 'status' => 'pending'],
            ['title' => 'Implementasi search bar', 'priority' => 'low', 'status' => 'done'],
            ['title' => 'Desain landing page baru', 'priority' => 'high', 'status' => 'pending'],
            ['title' => 'Setup CI/CD pipeline', 'priority' => 'medium', 'status' => 'in_progress'],
        ];

        foreach ($tasks as $task) {
            Task::create([
                'title' => $task['title'],
                'description' => 'Generated by DemoComboboxSeeder',
                'category_id' => $categories->random()->id,
                'assignee_id' => $users->random()->id,
                'priority' => $task['priority'],
                'status' => $task['status'],
            ]);
        }
    }
}
